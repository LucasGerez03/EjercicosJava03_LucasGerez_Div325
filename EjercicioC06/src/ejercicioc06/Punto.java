public class Punto {
    private int x;
    private int y;
    
    //------------------------------------------------
    //Constructor
    public Punto(int x, int y) {
        this.x = x;
        this.y = y;
    }
    
    //------------------------------------------------
    //getters

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
    
    
}
